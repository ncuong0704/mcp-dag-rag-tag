-- Docker POSTGRES_DB đã tạo sẵn database cong_ty_ban_le

-- Bảng sản phẩm
CREATE TABLE san_pham (
    ma_sp SERIAL PRIMARY KEY,
    ten_sp VARCHAR(200) NOT NULL,
    danh_muc VARCHAR(50) NOT NULL,
    gia_ban NUMERIC(15, 0) NOT NULL
);

-- Bảng khách hàng
CREATE TABLE khach_hang (
    ma_kh SERIAL PRIMARY KEY,
    ten_kh VARCHAR(200) NOT NULL,
    thanh_pho VARCHAR(50) NOT NULL,
    loai_kh VARCHAR(20) NOT NULL
);

-- Bảng nhân viên
CREATE TABLE nhan_vien (
    ma_nv SERIAL PRIMARY KEY,
    ten_nv VARCHAR(100) NOT NULL,
    phong_ban VARCHAR(50) NOT NULL
);

-- Bảng đơn hàng
CREATE TABLE don_hang (
    ma_dh SERIAL PRIMARY KEY,
    ma_kh INTEGER NOT NULL REFERENCES khach_hang(ma_kh),
    ma_nv INTEGER NOT NULL REFERENCES nhan_vien(ma_nv),
    ngay_dat DATE NOT NULL,
    trang_thai VARCHAR(20) NOT NULL
);

-- Bảng chi tiết đơn hàng
CREATE TABLE chi_tiet_don_hang (
    id SERIAL PRIMARY KEY,
    ma_dh INTEGER NOT NULL REFERENCES don_hang(ma_dh),
    ma_sp INTEGER NOT NULL REFERENCES san_pham(ma_sp),
    so_luong INTEGER NOT NULL CHECK (so_luong > 0),
    don_gia NUMERIC(15, 0) NOT NULL CHECK (don_gia >= 0)
);

